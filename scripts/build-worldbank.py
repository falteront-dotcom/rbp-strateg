#!/usr/bin/env python3
"""Fetch REAL authoritative data from the World Bank Open Data API.

Bakes live World Bank indicators (military expenditure, armed-forces personnel)
into `src/lib/data/world-bank.generated.ts`, with source attribution. This is
the app's REAL data layer (as opposed to open-source LLM estimates): every
figure carries the World Bank indicator code + year so it is auditable.

Indicators:
  MS.MIL.XPND.GD.ZS  Military expenditure (% of GDP)
  MS.MIL.XPND.CD     Military expenditure (current US$)
  MS.MIL.TOTL.P1     Armed forces personnel, total

Usage: python scripts/build-worldbank.py   (requires internet)
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src" / "lib" / "data"
DATA.mkdir(parents=True, exist_ok=True)

API = "https://api.worldbank.org/v2/country/all/indicator/{ind}?format=json&per_page=20000&date={year}"
INDICATORS = {
    "milSpendPctGdp": "MS.MIL.XPND.GD.ZS",
    "milSpendUsd": "MS.MIL.XPND.CD",
    "armedForcesPersonnel": "MS.MIL.TOTL.P1",
}

# ISO-3 mismatch: the app uses PHI (PHL), WB uses PHL. Also normalize Kosovo.
APP_ISO_FIX = {"PHL": "PHI", "XKX": "XKX"}
# WB aggregate region codes to skip (not real countries).
AGGREGATES = {
    "AFE", "AFW", "ARB", "CEB", "EAR", "EAS", "EAP", "TEA", "ECA", "ECS", "EMU",
    "EUU", "FCS", "HIC", "HPC", "IBD", "IBT", "IDA", "IDB", "IDX", "INX", "LAC",
    "LCN", "LDC", "LIC", "LMC", "LMY", "MEA", "MIC", "MNA", "NAC", "OED", "OSS",
    "PRE", "PSS", "PST", "SAS", "SSA", "SST", "TEC", "TLA", "TSA", "TSS", "UMC",
    "WLD", "KSV", "MNA",
}


def fetch_indicator(indicator: str, year: int) -> dict[str, float]:
    url = API.format(ind=indicator, year=year)
    with urllib.request.urlopen(url, timeout=60) as r:
        payload = json.load(r)
    rows = payload[1] if len(payload) > 1 else []
    out: dict[str, float] = {}
    for row in rows:
        iso = row.get("countryiso3code")
        val = row.get("value")
        if not iso or val is None:
            continue
        if iso in AGGREGATES:
            continue
        iso3 = APP_ISO_FIX.get(iso, iso)
        out[iso3] = float(val)
    return out


def fetch_latest(indicator: str, years: list[int]) -> tuple[dict[str, dict], int]:
    """Return {iso: {value, year}} using the most recent non-null year per country."""
    by_year = {y: fetch_indicator(indicator, y) for y in years}
    latest: dict[str, dict] = {}
    for y in years:  # years ascending; later overwrite earlier
        for iso, val in by_year[y].items():
            latest[iso] = {"value": val, "year": y}
    used_year = max(years)
    return latest, used_year


def main() -> None:
    years = [2018, 2019, 2020, 2021, 2022, 2023]
    mil_pct, _ = fetch_latest(INDICATORS["milSpendPctGdp"], years)
    mil_usd, _ = fetch_latest(INDICATORS["milSpendUsd"], years)
    personnel, _ = fetch_latest(INDICATORS["armedForcesPersonnel"], years)

    isos = sorted(set(mil_pct) | set(mil_usd) | set(personnel))

    out = [
        "/** GENERATED by scripts/build-worldbank.py — REAL World Bank Open Data (живые показатели). НЕ редактировать вручную. */",
        "",
        "export interface WorldBankEntry {",
        "  iso: string;",
        "  milSpendPctGdp: number | null;",
        "  milSpendPctGdpYear: number | null;",
        "  milSpendUsd: number | null;",
        "  milSpendUsdYear: number | null;",
        "  armedForcesPersonnel: number | null;",
        "  personnelYear: number | null;",
        "}",
        "",
        "/** Источник: World Bank Open Data (api.worldbank.org), индикаторы MS.MIL.*. */",
        "export const WORLD_BANK_SOURCE = \"World Bank Open Data\";",
        "export const WORLD_BANK_INDICATORS = {",
        '  milSpendPctGdp: "MS.MIL.XPND.GD.ZS",',
        '  milSpendUsd: "MS.MIL.XPND.CD",',
        '  armedForcesPersonnel: "MS.MIL.TOTL.P1",',
        "} as const;",
        "",
        "export const WORLD_BANK_DATA: readonly WorldBankEntry[] = [",
    ]

    def fmt(v: dict | None) -> str:
        if not v:
            return "null, null"
        return f"{v['value']}, {v['year']}"

    for iso in isos:
        p = mil_pct.get(iso)
        u = mil_usd.get(iso)
        per = personnel.get(iso)
        out.append("  {")
        out.append(f"    iso: {json.dumps(iso)},")
        out.append(f"    milSpendPctGdp: {fmt(p).split(', ')[0]},")
        out.append(f"    milSpendPctGdpYear: {fmt(p).split(', ')[1]},")
        out.append(f"    milSpendUsd: {fmt(u).split(', ')[0]},")
        out.append(f"    milSpendUsdYear: {fmt(u).split(', ')[1]},")
        out.append(f"    armedForcesPersonnel: {fmt(per).split(', ')[0]},")
        out.append(f"    personnelYear: {fmt(per).split(', ')[1]},")
        out.append("  },")
    out.append("];")
    out.append("")
    out.append("export const WORLD_BANK_INDEX: Readonly<Record<string, WorldBankEntry>> =")
    out.append("  Object.fromEntries(WORLD_BANK_DATA.map(d => [d.iso, d]));")
    out.append("")

    (DATA / "world-bank.generated.ts").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"OK: World Bank — {len(isos)} стран")
    print(f"  milSpendPctGdp: {len(mil_pct)} | milSpendUsd: {len(mil_usd)} | personnel: {len(personnel)}")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(f"FAIL: {e}", file=sys.stderr)
        sys.exit(1)
