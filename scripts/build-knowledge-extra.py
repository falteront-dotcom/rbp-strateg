def build_orders() -> int:
    rows: list = []
    for path in sorted(RESEARCH.glob("*.json")):
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        groups = []
        if isinstance(raw, dict) and isinstance(raw.get("orders"), list):
            groups = raw["orders"]
        elif isinstance(raw, list):
            groups = [r for r in raw if isinstance(r, dict) and "formations" in r]
        for grp in groups:
            iso = grp.get("iso")
            if not isinstance(iso, str) or len(iso) != 3:
                continue
            for f in grp.get("formations") or []:
                if isinstance(f, dict) and f.get("nameRu"):
                    rows.append({"iso": iso, **f})
    out = [HEADER]
    out.append("export interface OrderOfBattle {")
    out.append("  iso: string;")
    out.append("  nameRu: string;")
    out.append("  typeRu: string;")
    out.append("  branchRu: string;")
    out.append("  strengthRu: string;")
    out.append("  locationRu: string;")
    out.append("  noteRu: string | null;")
    out.append("}")
    out.append("")
    out.append("export const ORDER_OF_BATTLE: readonly OrderOfBattle[] = [")
    for f in rows:
        out.append("  {")
        out.append(f"    iso: {ts(f.get('iso'))},")
        out.append(f"    nameRu: {ts(f.get('nameRu') or '')},")
        out.append(f"    typeRu: {ts(f.get('typeRu') or '')},")
        out.append(f"    branchRu: {ts(f.get('branchRu') or '')},")
        out.append(f"    strengthRu: {ts(f.get('strengthRu') or '')},")
        out.append(f"    locationRu: {ts(f.get('locationRu') or '')},")
        note = f.get("noteRu")
        out.append(f"    noteRu: {ts(note)}" if note else "    noteRu: null")
        out.append("  },")
    out.append("];")
    out.append("")
    return write_lines("order-of-battle.generated.ts", out)


