// Волна 3 «Устойчивость в войне» — barrel export
// Аттриция (Ланчестер), выносливость запасов, мобилизация, проекция силы
// и входные данные топ-30 стран.
// РБП-Стратег 3.0
// ─────────────────────────────────────────────────────────────────────────────
//
// Состав модуля:
//   lanchester.ts — аттриционный симулятор: линейный и квадратичный
//     законы Ланчестера, модификаторы качества, террейна, превосходства
//     в РЭБ и в воздухе; пошаговая симуляция по дням с журналом потерь
//     и обменным соотношением; аналитические уравнения состояния;
//     условия победы — уничтожение, моральный распад, истощение;
//     пресеты сценариев и пакетный анализ чувствительности к массе.
//   endurance.ts — выносливость страны: месяцы до исчерпания по семи
//     категориям запасов (снаряды, ракеты, бронетехника, авиация,
//     личный состав, БПЛА, перехватчики ПВО) с учётом производства,
//     импорта, разгона промышленности и блокады; бутылочное горлышко
//     страны, рейтинг стран, сценарные пресеты, текстовый отчёт.
//   mobilization.ts — мобилизационная модель: волны мобилизации со
//     сроками призыва и обучения, кривая качества от длительности
//     обучения и номера волны, потолок из трёх ограничений
//     (демография, экономика, учебные кадры) с инвариантом
//     «волны не превышают потолок»; временная шкала сил, исторические
//     примеры мобилизаций, пресеты планов от усиления до тотальной войны.
//   projection.ts — проекция силы: экспоненциальное затухание боевого
//     потенциала с дистанцией по пяти доменам, сокращение эффективной
//     дистанции передовыми базами, множитель союзнической поддержки,
//     каталог из 15 мировых chokepoint'ов с пропускной способностью
//     маршрутов, театральные пресеты (Тайвань, Балтика, ЮКМ, Ормуз,
//     Чёрное море) и оценка снабжения театра в тоннах в сутки.
//   data/top30-sustainability.ts — входные данные: 30 стран, по каждой
//     семь категорий запасов с полями запаса, дневного расхода,
//     месячного производства и импорта, источником, годом винтажа
//     и флагом estimated; мобилизационная база; реестр источников.
//
// Самопроверки модуля: verify_warfare3.ts в корне репозитория.
// Все импорты внутри модуля — относительные; зависимости от остального
// проекта отсутствуют, модуль подключается к API/UI отдельным шагом.

