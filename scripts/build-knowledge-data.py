def build_history() -> int:
    rows: list[dict] = []
    for name in ("hist-1945-1999.json", "hist-2000-2025.json"):
        path = RESEARCH / "wave7" / name
        if not path.exists():
            print(f"SKIP: {path.relative_to(ROOT)}")
            continue
        raw = json.loads(path.read_text(encoding="utf-8"))
        chunk = raw.get("conflicts", raw) if isinstance(raw, dict) else raw
        if not isinstance(chunk, list):
            die(f"{name}: нет conflicts")
        for c in chunk:
            where = f"{name}:{c.get('id')}"
            if c.get("type") not in CONFLICT_TYPES:
                die(f"{where}: type {c.get('type')!r} вне enum")
            start, end = c.get("startYear"), c.get("endYear")
            for y in (start, end):
                if not isinstance(y, int) or isinstance(y, bool):
                    die(f"{where}: год не целое: {y!r}")
            if start > end:
                die(f"{where}: startYear > endYear")
            rows.append(c)
    # Межпериодные конфликты могут попасть в оба файла — суффиксуем id, а не падаем.
    seen_ids: set[str] = set()
    for r in rows:
        base = r["id"]
        cid = base
        k = 2
        while cid in seen_ids:
            cid = f"{base}-{k}"
            k += 1
        r["id"] = cid
        seen_ids.add(cid)

    out = [HEADER]
    out.append("export type ConflictType =")
    out.append("  | " + " | ".join(f'"{t}"' for t in CONFLICT_TYPES) + ";")
    out.append("")
    out.append("export interface HistoricalConflict {")
    out.append("  id: string;")
    out.append("  nameRu: string;")
    out.append("  startYear: number;")
    out.append("  endYear: number;")
    out.append("  region: string;")
    out.append("  type: ConflictType;")
    out.append("  belligerents: string[];")
    out.append("  isoCodes: string[];")
    out.append("  fatalities: number | null;")
    out.append("  outcomeRu: string;")
    out.append("  summaryRu: string;")
    out.append("}")
    out.append("")
    out.append("export const HISTORICAL_CONFLICTS: readonly HistoricalConflict[] = [")
    for c in rows:
        c = clean_fields(dict(c))
        where = f"hist:{c.get('id')}"
        out.append("  {")
        out.append(f"    id: {ts_str(c['id'])},")
        out.append(f"    nameRu: {ts_str(c['nameRu'])},")
        out.append(f"    startYear: {ts_num(c['startYear'], 'startYear', where)},")
        out.append(f"    endYear: {ts_num(c['endYear'], 'endYear', where)},")
        out.append(f"    region: {ts_str(c['region'])},")
        out.append(f"    type: {ts_str(c['type'])},")
        out.append(f"    belligerents: {ts_str_array(c['belligerents'], where, 'belligerents')},")
        out.append(f"    isoCodes: {ts_iso_array(c['isoCodes'], where)},")
        out.append(f"    fatalities: {ts_num(c.get('fatalities'), 'fatalities', where)},")
        out.append(f"    outcomeRu: {ts_str(c['outcomeRu'])},")
        out.append(f"    summaryRu: {ts_str(c['summaryRu'])},")
        out.append("  },")
    out.append("];")
    out.append("")
    (DATA / "conflict-history.generated.ts").write_text("\n".join(out), encoding="utf-8", newline="\n")
    return len(rows)


