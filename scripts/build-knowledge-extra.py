def build_budgets() -> int:
    series = load("budgets.json", "series")
    out = [HEADER]
    out.append("export interface BudgetPoint { year: number; usdBn: number | null; pctGdp: number | null; }")
    out.append("export interface BudgetSeries { iso: string; points: BudgetPoint[]; }")
    out.append("")
    out.append("export const BUDGET_SERIES: readonly BudgetSeries[] = [")
    for s in series:
        iso = s.get("iso")
        if not isinstance(iso, str) or len(iso) != 3:
            missed.append(f"budget iso={iso!r}")
            continue
        out.append("  {")
        out.append(f"    iso: {ts(iso)},")
        out.append("    points: [")
        for pt in s.get("points") or []:
            year = pt.get("year")
            if not isinstance(year, int):
                continue
            out.append(f"      {{ year: {year}, usdBn: {num(pt.get('usdBn'), 'usdBn')}, pctGdp: {num(pt.get('pctGdp'), 'pctGdp')} }},")
        out.append("    ],")
        out.append("  },")
    out.append("];")
    out.append("")
    return write_lines("budgets.generated.ts", out)


