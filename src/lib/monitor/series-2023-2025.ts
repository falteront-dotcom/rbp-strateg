import {
  SnapshotRegistry,
  type CountrySnapshot,
} from "./snapshots";

/** Собрать реестр рядов 2023–2025. */
export function buildSeriesRegistry(): SnapshotRegistry {
  const registry = new SnapshotRegistry();
  registry.addMany(ALL_SNAPSHOTS);
  return registry;
}

/** Ряды по странам: ISO3 → снапшоты по годам. */
export function seriesByCountry(): Map<string, CountrySnapshot[]> {
  const map = new Map<string, CountrySnapshot[]>();
  for (const snapshot of ALL_SNAPSHOTS) {
    const list = map.get(snapshot.iso3) ?? [];
    list.push(snapshot);
    map.set(snapshot.iso3, list);
  }
  for (const list of map.values()) {
    list.sort((a, b) => a.year - b.year);
  }
  return map;
}

