// ─── Доступ к рубрикам ───────────────────────────────────────────────────────

/** Все рубрики одним объектом */
export const RUBRICS: Record<RubricKind, Rubric> = {
  c4isr: C4ISR_RUBRIC,
  ew: EW_RUBRIC,
  morale: MORALE_RUBRIC,
};

/** Уровень рубрики по баллу (балл округляется и зажимается в 1–10) */
export function getRubricLevel(kind: RubricKind, score: number): RubricLevel {
  const rubric: Rubric = RUBRICS[kind];
  const clamped: number = Math.min(Math.max(Math.round(score), 1), 10);
  const level: RubricLevel | undefined = rubric.levels[clamped - 1];
  if (level === undefined) {
    throw new Error(`Rubric ${kind} has no level for score ${clamped}`);
  }
  return level;
}

/** Проверка допустимости балла рубрики: конечное число в диапазоне 1–10 */
export function validateRubricScore(
  kind: RubricKind,
  score: number,
): { valid: true } | { valid: false; errors: string[] } {
  const errors: string[] = [];
  if (typeof score !== "number" || !Number.isFinite(score)) {
    errors.push(`Score for ${kind} must be a finite number, got ${score}`);
  } else if (score < 1 || score > 10) {
    errors.push(`Score for ${kind} must be within 1–10, got ${score}`);
  }
  if (errors.length > 0) {
    return { valid: false, errors };
  }
  return { valid: true };
}

// ─── Два независимых скоринг-прохода ─────────────────────────────────────────

/** Результат сведения двух независимых оценок */
export interface TwoScorerResult {
  /** Итоговый балл: среднее двух проходов */
  combined: number;
  /** Абсолютное расхождение проходов */
  discrepancy: number;
  /** true, если расхождение > 2: оценка не публикуется без арбитража */
  adjudicationRequired: boolean;
  /** Методическая пометка для журнала оценки */
  noteRu: string;
}

/** Порог расхождения, требующий арбитража третьего аналитика */
export const ADJUDICATION_THRESHOLD = 2;

/**
 * Сводит два независимых скоринг-прохода по рубрике.
 * Независимость — ключевое требование: второй скорер не видит балл
 * первого до фиксации своего, иначе процедура превращается в подгонку.
 */
export function combineTwoScorers(
  kind: RubricKind,
  firstScore: number,
  secondScore: number,
): TwoScorerResult {
  const first: { valid: true } | { valid: false; errors: string[] } =
    validateRubricScore(kind, firstScore);
  if (!first.valid) {
    throw new Error(first.errors.join("; "));
  }
  const second: { valid: true } | { valid: false; errors: string[] } =
    validateRubricScore(kind, secondScore);
  if (!second.valid) {
    throw new Error(second.errors.join("; "));
  }
  const discrepancy: number = Math.abs(firstScore - secondScore);
  const adjudicationRequired: boolean = discrepancy > ADJUDICATION_THRESHOLD;
  const combined: number = (firstScore + secondScore) / 2;
  const noteRu: string = adjudicationRequired
    ? `Расхождение ${discrepancy.toFixed(1)} > ${ADJUDICATION_THRESHOLD}: требуется арбитраж, среднее публиковать нельзя.`
    : `Расхождение ${discrepancy.toFixed(1)} в пределах допуска: итог — среднее двух проходов.`;
  return { combined, discrepancy, adjudicationRequired, noteRu };
}

