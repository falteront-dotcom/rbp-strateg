export interface DeceptionRiskInput {
  observedIndicatorIds: string[];
  /** Ключевой вывод держится на одном канале сбора. */
  singleChannelDependence: boolean;
  /** Противник осведомлён о наших средствах наблюдения по этому каналу. */
  adversaryAwareOfCollection: boolean;
}

export interface DeceptionRiskResult {
  score: number;
  level: "low" | "moderate" | "high" | "critical";
  byChannel: Array<{ channel: DeceptionChannel; count: number; maxLevel: RedFlagLevel }>;
  recommendationsRu: string[];
}

const LEVEL_ORDER: RedFlagLevel[] = ["low", "medium", "high"];

/** Оценка риска обмана по отмеченным индикаторам каталога. */
export function assessDeceptionRisk(input: DeceptionRiskInput): DeceptionRiskResult {
  const found = DECEPTION_INDICATORS.filter((i) => input.observedIndicatorIds.includes(i.id));
  let score = 0;
  const byChannelMap = new Map<DeceptionChannel, { count: number; maxLevel: RedFlagLevel }>();
  for (const ind of found) {
    score += ind.redFlagLevel === "high" ? 18 : ind.redFlagLevel === "medium" ? 10 : 5;
    const entry = byChannelMap.get(ind.channel) ?? { count: 0, maxLevel: "low" as RedFlagLevel };
    entry.count += 1;
    if (LEVEL_ORDER.indexOf(ind.redFlagLevel) > LEVEL_ORDER.indexOf(entry.maxLevel)) {
      entry.maxLevel = ind.redFlagLevel;
    }
    byChannelMap.set(ind.channel, entry);
  }
  if (input.singleChannelDependence) {
    score += 20;
  }
  if (input.adversaryAwareOfCollection) {
    score += 15;
  }
  score = Math.min(100, score);
  const level: DeceptionRiskResult["level"] =
    score >= 70 ? "critical" : score >= 45 ? "high" : score >= 20 ? "moderate" : "low";
  const recommendationsRu: string[] = [];
  if (input.singleChannelDependence) {
    recommendationsRu.push("Вывод держится на одном канале: поставить задачу независимого подтверждения до публикации сводки.");
  }
  if (input.adversaryAwareOfCollection) {
    recommendationsRu.push("Противник знает о канале наблюдения: все «удобные» свидетельства канала считать подозреваемыми на подачу.");
  }
  if (byChannelMap.size >= 3) {
    recommendationsRu.push("Индикаторы обмана в трёх и более каналах: рассмотреть гипотезу координированной операции D&D как отдельную строку в ACH.");
  }
  if (level === "critical" || level === "high") {
    recommendationsRu.push("Запустить red-team проход по чек-листу RED_TEAM_CHECKLIST_RU и понизить confidence ключевых свидетельств до результатов проверки.");
  }
  if (recommendationsRu.length === 0) {
    recommendationsRu.push("Явных признаков координированного обмана не выявлено; стандартная верификация свидетельств сохраняется.");
  }
  return {
    score,
    level,
    byChannel: [...byChannelMap.entries()].map(([channel, v]) => ({
      channel,
      count: v.count,
      maxLevel: v.maxLevel,
    })),
    recommendationsRu,
  };
}

/** Индикаторы обмана одного канала для чек-листа аналитика. */
export function deceptionIndicatorsByChannel(channel: DeceptionChannel): DeceptionIndicator[] {
  return DECEPTION_INDICATORS.filter((i) => i.channel === channel);
}
