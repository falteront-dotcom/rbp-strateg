// источник или аудит, и помечен как приблизительный в noteRu.

import type { Data3Grade } from "./verify-engine";

/** Основание значения бюджета-2026. */
export type Budget2026Basis = "request" | "enacted" | "planned" | "estimate";

/** Одна строка слоя официальных бюджетов 2026 года. */
export interface Budget2026Entry {
  /** ISO 3166-1 alpha-3 */
  iso3: string;
  /** Название страны (EN) */
  name: string;
  /** Название страны (RU) */
  nameRu: string;
  /** Финансовый год/период, к которому относится бюджет (RU) */
  fiscalLabelRu: string;
  /** Сумма в национальной валюте, как публикует источник */
  amountOriginal: string;
  /** Приблизительный эквивалент, млрд долл. США; null — источник не даёт */
  amountUsdBn: number | null;
  /** Доля ВВП, %; null — источник не даёт */
  pctGdp: number | null;
  /** Основание: запрос / принято / план / вторичная оценка */
  basis: Budget2026Basis;
  /** Источник значения */
  source: string;
  /** Дата источника (ISO или месяц/год RU — как зафиксировано аудитом) */
  sourceDate: string;
  /** Значение — оценка, а не официальная публикация первоисточника */
  estimated: boolean;
  /** Адмиралтейский грейд значения */
  grade: Data3Grade;
  /** Пометка RU: состав суммы, статус принятия, оговорки */
  noteRu: string;
}

