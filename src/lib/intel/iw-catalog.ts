/** Порядок фаз подготовки: от самой ранней к самой поздней. */
const PHASE_ORDER: Record<IWPhase, number> = {
  strategic: 0,
  operational: 1,
  tactical: 2,
  imminent: 3,
};

/** Индикаторы одной категории. */
export function indicatorsByCategory(category: IWCategory): IWIndicator[] {
  return IW_CATALOG.filter((i) => i.category === category);
}

/** Поиск индикатора по id; undefined, если такого нет. */
export function findIndicator(id: string): IWIndicator | undefined {
  return IW_CATALOG.find((i) => i.id === id);
}

/** Индикаторы, наблюдаемые указанной дисциплиной сбора. */
export function indicatorsByDiscipline(discipline: IWDiscipline): IWIndicator[] {
  return IW_CATALOG.filter((i) => i.disciplines.includes(discipline));
}

/**
 * Индикаторы, относящиеся к фазам не позднее указанной:
 * indicatorsByPhase("operational") вернёт стратегические и оперативные.
 */
export function indicatorsByPhase(upto: IWPhase): IWIndicator[] {
  const limit = PHASE_ORDER[upto];
  return IW_CATALOG.filter((i) => PHASE_ORDER[i.phase] <= limit);
}
