# ────────────────────────────────────────────────────────────────────────────
# Country dossiers (3 files)
# ────────────────────────────────────────────────────────────────────────────

def build_dossiers() -> int:
    # mimo-агенты пишут досье то в dossier-N.json (обёртка {"dossiers":[...]}),
    # то голыми списками в _pN.json. Сканируем всё и отбираем по содержимому.
    rows: list = []
    for path in sorted(RESEARCH.glob("*.json")):
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        candidates: list = []
        if isinstance(raw, dict) and isinstance(raw.get("dossiers"), list):
            candidates = raw["dossiers"]
        elif isinstance(raw, list):
            candidates = raw
        for rec in candidates:
            if isinstance(rec, dict) and "overviewRu" in rec and "iso" in rec:
                rows.append(rec)
    out = [HEADER]
    out.append("export interface CountryDossier {")
    out.append("  iso: string;")
    out.append("  overviewRu: string;")
    out.append("  geographyRu: string;")
    out.append("  economyRu: string;")
    out.append("  militaryStructureRu: string;")
    out.append("  strategicRoleRu: string;")
    out.append("  keyFactsRu: string[];")
    out.append("}")
    out.append("")
    out.append("export const COUNTRY_DOSSIERS: readonly CountryDossier[] = [")
    n = 0
    seen_iso: set[str] = set()
    for d in rows:
        iso = d.get("iso")
        if not isinstance(iso, str) or len(iso) != 3:
            missed.append(f"dossier iso={iso!r}")
            continue
        if iso in seen_iso:
            continue
        seen_iso.add(iso)
        out.append("  {")
        out.append(f"    iso: {ts(iso)},")
        out.append(f"    overviewRu: {ts(d.get('overviewRu') or '')},")
        out.append(f"    geographyRu: {ts(d.get('geographyRu') or '')},")
        out.append(f"    economyRu: {ts(d.get('economyRu') or '')},")
        out.append(f"    militaryStructureRu: {ts(d.get('militaryStructureRu') or '')},")
        out.append(f"    strategicRoleRu: {ts(d.get('strategicRoleRu') or '')},")
        out.append(f"    keyFactsRu: {arr(d.get('keyFactsRu'))},")
        out.append("  },")
        n += 1
    out.append("];")
    out.append("")
    out.append("export const DOSSIER_INDEX: Readonly<Record<string, CountryDossier>> =")
    out.append("  Object.fromEntries(COUNTRY_DOSSIERS.map(d => [d.iso, d]));")
    out.append("")
    return write_lines("dossiers.generated.ts", out)


def build_weapons() -> int:
    # mimo может писать weapons-ground/air/naval/missile.json и частями (_w*.json).
    rows: list = []
    for path in sorted(RESEARCH.glob("*.json")):
        if not (path.name.startswith("weapons") or path.name.startswith("_w")):
            continue
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        cand = raw.get("weapons") if isinstance(raw, dict) and isinstance(raw.get("weapons"), list) else (raw if isinstance(raw, list) else [])
        for r in cand:
            if isinstance(r, dict) and "name" in r and "category" in r:
                rows.append(r)
    out = [HEADER]
    out.append("export interface WeaponSpec {")
    out.append("  id: string;")
    out.append("  name: string;")
    out.append("  nameRu: string;")
    out.append("  category: string;")
    out.append("  originIso: string;")
