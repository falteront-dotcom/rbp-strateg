/**
 * Единый источник правды об охвате стран (Wave 0, ROADMAP-3.0 п. 11).
 *
 * Чем определяется покрытие: тем, какие наборы данных загружены в БД.
 * В проекте два режима, и у каждого — своё фактическое число:
 *
 * 1. Кураторский сид (seed) — три ручных набора в src/db/seed/:
 *    top20-countries (20) + extended-countries (31) + additional-countries (8).
 *    Это та самая фикстура из 59 стран, на которую опираются README
 *    («59 стран в локальной seed-БД»), e2e-контракты и smoke-тест пайплайна.
 *
 * 2. Полный набор (generated) — сид + world-countries (136) = 195 стран.
 *    Именно столько сидит серверный bootstrap (src/db/bootstrap.ts) и именно
 *    это число стоит в коммите «полный продакшн: 195 стран».
 *
 * Расхождение с «263 страны» в описании репозитория: 263 — это количество
 * записей в листинге GFP (globalfirepower.com), откуда взята часть исходных
 * данных; листинг GFP включает не только суверенные государства, но и
 * территории/зависимые образования. Странами проекта они не являются:
 * покрытие проекта — 195 (полный режим) и 59 (сид-режим), других чисел
 * в интерфейсах, README и описаниях быть не должно.
 */

/** Страны в кураторском сиде: top20 (20) + extended (31) + additional (8). */
export const SEED_COUNTRIES_COVERED = 59;

/** Страны в полном наборе: сид (59) + world-countries (136). */
export const GENERATED_COUNTRIES_COVERED = 195;

/**
 * Фактическое покрытие по умолчанию (полный продакшн-режим, bootstrap).
 * Использовать это значение везде, где UI/API сообщают «стран в базе».
 */
export const COUNTRIES_COVERED = GENERATED_COUNTRIES_COVERED;

/**
 * Число записей в исходном листинге GFP. НЕ является покрытием проекта —
 * константа существует только чтобы зафиксировать происхождение цифры 263
 * из описания репозитория и не дать ей снова выдать себя за охват.
 */
export const GFP_LISTING_ENTRIES = 263;
