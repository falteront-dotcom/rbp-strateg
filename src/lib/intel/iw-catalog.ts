// Методология I&W восходит к практике стратегического предупреждения
// (Cynthia Grabo, Handbook of Warning Intelligence): война редко начинается
// без наблюдаемой подготовки, а подготовка оставляет следы в логистике,
// медицине, финансах и дипломатии задолго до первых выстрелов.
// Правила каталога:
// — одиночный индикатор не является предупреждением: срабатывает паттерн;
// — у каждого индикатора есть мирное объяснение (falsePositiveRu) — аналитик
//   обязан проверить его раньше, чем военное;
// — вес отражает диагностичность, а не заметность: тихая закупка крови
//   весит больше, чем громкое заявление политика.

