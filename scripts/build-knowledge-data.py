#!/usr/bin/env python3
"""Build knowledge-pack generated TS from wave6 + wave7 research JSON.

Reads:
  test-results/research/wave6/equip-*.json   (equipment inventories)
  test-results/research/wave7/*.json         (history, industry, treaties,
                                              doctrines, transfers, exercises)

Writes (src/lib/data/):
  equipment.generated.ts
  conflict-history.generated.ts
  defense-industry.generated.ts
  treaties.generated.ts
  doctrines.generated.ts
  transfers.generated.ts
  exercises.generated.ts

Records with long Russian text are pretty-printed (readable), short records
stay one-per-line. All files carry honest headers with source caveats.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESEARCH = ROOT / "test-results" / "research"
DATA = ROOT / "src" / "lib" / "data"
DATA.mkdir(parents=True, exist_ok=True)

EQUIPMENT_CATS = [
    "tank", "ifv", "apc", "arty", "mlrs", "sam", "fighter", "attack",
    "transport", "uav", "heli", "heli_attack", "destroyer", "frigate",
    "cruiser", "corvette", "submarine", "carrier", "patrol", "amphib",
    "icbm", "slbm",
]
CONFLICT_TYPES = ["interstate", "civil", "colonial", "border", "insurgency",
                  "proxy", "world"]
TREATY_TYPES = ["defense", "nonprolif", "arms_control", "security", "neutrality"]
TRANSFER_STATUSES = ["delivered", "contracted", "cancelled"]

HEADER = "/** GENERATED by scripts/build-knowledge-data.py — открытые источники (IISS/GFP/SIPRI-уровень оценок). НЕ редактировать вручную. */\n\n"


def die(msg: str) -> None:
    print(f"FAIL: {msg}", file=sys.stderr)
    sys.exit(1)


def load8(name: str, key: str) -> list:
    path = RESEARCH / "wave8" / name
    if not path.exists():
        return []
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return []
    if isinstance(raw, dict):
        return raw.get(key) or []
    return raw if isinstance(raw, list) else []


def merge8(rows: list, name: str, key: str, pk: str) -> list:
    seen = {r.get(pk) for r in rows if isinstance(r, dict)}
    for r in load8(name, key):
        if isinstance(r, dict) and r.get(pk) and r.get(pk) not in seen:
            seen.add(r.get(pk))
            rows.append(r)
    return rows


def merge8_tuple(rows: list, name: str, key: str, fields: tuple) -> list:
    seen = {tuple(r.get(f) for f in fields) for r in rows if isinstance(r, dict)}
    for r in load8(name, key):
        if not isinstance(r, dict):
            continue
        k = tuple(r.get(f) for f in fields)
        if k not in seen:
            seen.add(k)
            rows.append(r)
    return rows


def ts_str(value: str) -> str:
    if isinstance(value, str):
        value = clean_text(value)
    return json.dumps(value, ensure_ascii=False)


CJK_RE = re.compile(r"[\u3000-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]+")


def clean_text(value: str) -> str:
    """Убирает CJK-вкрапления, попавшие в поля от генератора, и мусорные скобки."""
    s = CJK_RE.sub(" ", value)
    s = re.sub(r"\(\s*\)", "", s)
    s = re.sub(r"\s{2,}", " ", s)
    return s.strip()


def clean_fields(row: dict) -> dict:
    for key in ("itemRu", "nameRu", "noteRu", "model", "warheadRu", "outcomeRu", "summaryRu", "scaleRu", "hq"):
        v = row.get(key)
        if isinstance(v, str):
            row[key] = clean_text(v)
    return row


def ts_num(value, field: str, where: str) -> str:
    if value is None:
        return "null"
    if not isinstance(value, (int, float)) or isinstance(value, bool):
        die(f"{where}: {field} не число: {value!r}")
    return str(value)


def ts_bool(value, field: str, where: str) -> str:
    if not isinstance(value, bool):
        die(f"{where}: {field} не bool: {value!r}")
    return "true" if value else "false"


def ts_iso(value, where: str, field: str = "iso") -> str:
    if not isinstance(value, str) or len(value) != 3 or value != value.upper() or not value.isalpha():
        die(f"{where}: {field} не ISO3: {value!r}")
    return ts_str(value)


def ts_opt_str(value, where: str, field: str) -> str:
    if value is None:
        return "null"
    if not isinstance(value, str):
        die(f"{where}: {field} не строка: {value!r}")
    return ts_str(value)


def ts_str_array(value, where: str, field: str) -> str:
    if not isinstance(value, list) or not all(isinstance(x, str) for x in value):
        die(f"{where}: {field} не массив строк")
    return "[" + ", ".join(ts_str(x) for x in value) + "]"


def ts_iso_array(value, where: str, field: str = "isoCodes") -> str:
    if not isinstance(value, list):
        die(f"{where}: {field} не массив")
    return "[" + ", ".join(ts_iso(x, where, field) for x in value) + "]"


