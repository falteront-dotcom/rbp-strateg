def build_equipment() -> tuple[int, int]:
    wave6 = RESEARCH / "wave6"
    files = sorted(wave6.glob("equip-*.json"))
    if not files:
        die("нет файлов wave6/equip-*.json")

    valid_iso: set[str] = set()
    for lst in wave6.glob("list-*.txt"):
        valid_iso.update(x.strip() for x in lst.read_text(encoding="utf-8").splitlines() if x.strip())

    countries: list[dict] = []
    seen_iso: set[str] = set()
    total_entries = 0

    for path in files:
        raw = json.loads(path.read_text(encoding="utf-8"))
        rows = raw.get("countries", raw) if isinstance(raw, dict) else raw
        if not isinstance(rows, list):
            die(f"{path.name}: нет списка countries")
        for country in rows:
            iso = country.get("iso")
            where = f"{path.name}:{iso}"
            if iso not in valid_iso:
                die(f"{where}: iso вне списка 195")
            if iso in seen_iso:
                die(f"{where}: дубль iso между файлами")
            seen_iso.add(iso)
            entries: list[str] = []
            seen_model: set[tuple[str, str]] = set()
            for entry in country.get("entries", []):
                cat = entry.get("cat")
                model = entry.get("model")
                count = entry.get("count")
                if cat not in EQUIPMENT_CATS:
                    die(f"{where}: cat {cat!r} вне enum")
                if not isinstance(model, str) or not model.strip():
                    die(f"{where}: model пуст")
                if not isinstance(count, int) or isinstance(count, bool) or count <= 0:
                    die(f"{where}: count {count!r} не целое >0")
                key = (cat, model)
                if key in seen_model:
                    die(f"{where}: дубль {cat}/{model}")
                seen_model.add(key)
                note = entry.get("note")
                if note is not None and not isinstance(note, str):
                    die(f"{where}: note не строка")
                parts = [f"cat: {ts_str(cat)}", f"model: {ts_str(model)}", f"count: {count}"]
                if note:
                    parts.append(f"note: {ts_str(note)}")
                entries.append("        { " + ", ".join(parts) + " },")
            total_entries += len(entries)
            countries.append((iso, entries))

    out = [HEADER]
    out.append("export type EquipmentCat =")
    for i, cat in enumerate(EQUIPMENT_CATS):
        sep = " |" if i < len(EQUIPMENT_CATS) - 1 else ";"
        out.append(f'  | "{cat}"{sep}'.replace("| \"tank\"", "\"tank\""))
    out[-1] = out[-1].rstrip("|;") + ";" if False else out[-1]
    # rebuild the union cleanly
    out = out[:2]
    out.append("  | ".join(f'"{c}"' for c in EQUIPMENT_CATS) + ";")
    out.append("")
    out.append("export interface EquipmentEntry {")
    out.append("  cat: EquipmentCat;")
    out.append("  model: string;")
    out.append("  count: number;")
    out.append("  note?: string;")
    out.append("}")
    out.append("")
    out.append("export interface CountryEquipment {")
    out.append("  iso: string;")
    out.append("  entries: EquipmentEntry[];")
    out.append("}")
    out.append("")
    out.append(f"export const EQUIPMENT_BY_COUNTRY: readonly CountryEquipment[] = [")
    for iso, entries in countries:
        out.append("  {")
        out.append(f"    iso: {ts_str(iso)},")
        out.append("    entries: [")
        out.extend(entries)
        out.append("    ],")
        out.append("  },")
    out.append("];")
    out.append("")
    out.append("export const EQUIPMENT_INDEX: Readonly<Record<string, CountryEquipment>> =")
    out.append("  Object.fromEntries(EQUIPMENT_BY_COUNTRY.map(c => [c.iso, c]));")
    out.append("")

    (DATA / "equipment.generated.ts").write_text("\n".join(out), encoding="utf-8", newline="\n")
    return len(countries), total_entries


