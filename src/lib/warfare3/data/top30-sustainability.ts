/** Одна категория запасов: запас, расход, производство, импорт, провенанс */
export interface StockpileCategoryData {
  /** Стартовый запас на начало моделирования, в единицах категории */
  stock: number;
  /** Дневной расход при высокой интенсивности боевых действий */
  dailyConsumption: number;
  /** Месячное производство (включая восстановление для бронетехники) */
  monthlyProduction: number;
  /** Месячный импорт и внешние поставки */
  monthlyImports: number;
  /** Единица измерения категории */
  unit: string;
  /** Источник оценки */
  source: string;
  /** Год винтажа оценки */
  year: number;
  /** true — значение оценочное, официальной публикации нет */
  estimated: boolean;
}

/** Идентификаторы категорий истощения */
export type EnduranceCategoryId =
  | "artilleryShells"
  | "rocketsMissiles"
  | "armorVehicles"
  | "aviationPlatforms"
  | "personnel"
  | "drones"
  | "airDefenseInterceptors";

/** Мобилизационная база страны */
export interface MobilizationBaseData {
  /** Население страны, млн человек */
  populationMillions: number;
  /** Население трудоспособного возраста, млн человек */
  workingAgeMillions: number;
  /** Годных к военной службе, млн человек */
  fitForServiceMillions: number;
  /** Действующий личный состав, человек */
  activePersonnel: number;
  /** Обученный резерв первой очереди, человек */
  trainedReserve: number;
  /** Годовой призыв/набор в мирное время, человек в год */
  annualIntake: number;
  /**
   * Предельная устойчивая доля трудоспособного населения под ружьём, %.
   * Выше этого порога мобилизация разрушает экономику быстрее,
   * чем наращивает боевую мощь (исторический диапазон 5–15%).
   */
  maxSustainableSharePct: number;
  /** Источник оценки */
  source: string;
  /** Год винтажа оценки */
  year: number;
  /** true — значение оценочное */
  estimated: boolean;
}

/** Полный профиль устойчивости страны */
export interface CountrySustainabilityProfile {
  /** ISO3-код страны */
  iso3: string;
  /** Название на русском */
  nameRu: string;
  /** Название на английском */
  nameEn: string;
  /** Регион */
  region: string;
  /** Категории запасов по идентификаторам */
  categories: Record<EnduranceCategoryId, StockpileCategoryData>;
  /** Мобилизационная база */
  mobilizationBase: MobilizationBaseData;
  /** Короткий аналитический комментарий по устойчивости страны */
  commentRu: string;
}

