#!/usr/bin/env python3
"""Build extra knowledge generated TS from wave8 research JSON (mimo batch).

Reads test-results/research/wave8/*.json and writes src/lib/data/*.generated.ts
for the wave-8 domains: missiles, air-defense, navy, space/cyber, budgets,
personnel, infrastructure, chokepoints, country dossiers. Second-tier files
(industry2/doctrines2/treaties2/transfers2/exercises2) are merged into the
matching core modules by `build-knowledge-data.py` on the next run.

Parsing is TOLERANT: malformed records are skipped with a warning rather than
aborting the build (the generator model may deviate slightly from the schema).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESEARCH = ROOT / "test-results" / "research" / "wave8"
DATA = ROOT / "src" / "lib" / "data"
DATA.mkdir(parents=True, exist_ok=True)

HEADER = "/** GENERATED by scripts/build-knowledge-extra.py — открытые источники (оценки IISS/GFP/SIPRI). НЕ редактировать вручную. */\n\n"

missed: list[str] = []


def load(name: str, key: str) -> list:
    """Load wave8/<name>.json and return its top-level `key` array (tolerant)."""
    path = RESEARCH / name
    if not path.exists():
        print(f"SKIP: {path.name}")
        return []
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except Exception as e:
        missed.append(f"{path.name}: JSON {e}")
        print(f"WARN: {path.name}: {e}")
        return []
    rows = raw.get(key) if isinstance(raw, dict) else raw
    if not isinstance(rows, list):
        rows = []
    return rows


def ts(value) -> str:
    if isinstance(value, str):
        value = clean_text(value)
    return json.dumps(value, ensure_ascii=False)


CJK_RE = re.compile(r"[\u3000-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]+")


def clean_text(value: str) -> str:
    s = CJK_RE.sub(" ", value)
    s = re.sub(r"\(\s*\)", "", s)
    s = re.sub(r"\s{2,}", " ", s)
    return s.strip()


def cjk_safe(value: str | None) -> str | None:
    return clean_text(value) if isinstance(value, str) else value


def num(value, field: str):
    if value is None:
        return "null"
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        missed.append(f"{field}={value!r}")
        return "null"
    return str(value)


def arr(value) -> str:
    if not isinstance(value, list):
        return "[]"
    return "[" + ", ".join(ts(x) for x in value if isinstance(x, (str, int, float))) + "]"


def write_lines(filename: str, lines: list[str]) -> int:
    (DATA / filename).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return sum(1 for l in lines)


