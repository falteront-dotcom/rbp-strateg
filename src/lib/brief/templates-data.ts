// ─────────────────────────────────────────────────────────────────────────────
//
// Это не «рыба» для копирования, а эталонные примеры дисциплины формата:
// — каждое суждение снабжено вероятностью, уверенностью и основанием;
// — грейды источников честные: открытые базы (SIPRI, IISS) — B, оценки
//   профильных центров — C, заявления сторон конфликта — D и ниже;
// — альтернативы сформулированы так, чтобы их можно было различить
//   наблюдением, а не вкусом аналитика.
// Тексты сознательно избегают абсолютных формулировок и внешкальных
// вероятностных слов — сгенерированные из них сводки проходят валидатор
// ICD 203 из модуля intel.

import type { AdmiraltyGrade } from "../intel/admiralty";
import type {
  BriefAlternative,
  BriefInput,
  BriefKind,
  BriefSource,
  KeyJudgment,
} from "./brief-generator";

/** Приложение к шаблону: хроника и лист наблюдения. */
export interface TemplateAnnex {
  /** Тип сводки, к которой относится приложение. */
  kind: BriefKind;
  /** Ключевые события, формирующие контекст оценки. */
  timeline: AnnexEvent[];
  /** Пункты листа наблюдения на следующий период. */
  watchItems: WatchItem[];
}

/** Событие хроники приложения. */
export interface AnnexEvent {
  /** Период или дата события. */
  periodRu: string;
  /** Что произошло. */
  eventRu: string;
  /** Значение события для оценки. */
  significanceRu: string;
}

/** Пункт листа наблюдения. */
export interface WatchItem {
  /** Что наблюдать. */
  itemRu: string;
  /** Почему это важно и что наблюдение изменит. */
  rationaleRu: string;
}

/** Фрагмент суждения для библиотеки переиспользуемых блоков. */
export interface JudgmentFragment {
  /** Объект фрагмента (страна/коалиция). */
  subjectRu: string;
  /** Тема фрагмента. */
  topicRu: string;
  /** Готовое суждение. */
  judgment: KeyJudgment;
  /** Базовый грейд источников фрагмента. */
  typicalGrade: AdmiraltyGrade;
}

function src(
  nameRu: string,
  source: string,
  info: 1 | 2 | 3 | 4 | 5 | 6,
  contributionRu: string,
): BriefSource {
  return {
    nameRu: nameRu,
    grade: {
      source: source as AdmiraltyGrade["source"],
      info: info,
    },
    contributionRu: contributionRu,
  };
}

