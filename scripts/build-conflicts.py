# -*- coding: utf-8 -*-
"""
Build the live conflict-zones layer from research agent output.

Reads conflicts-*.json from test-results/research/wave2/ and
test-results/research/wave3/, validates every
record and emits src/lib/facilities/conflict-zones.generated.ts.

Run:  python scripts/build-conflicts.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WAVE2 = ROOT / "test-results" / "research" / "wave2"
WAVE3 = ROOT / "test-results" / "research" / "wave3"
OUT = ROOT / "src/lib/facilities" / "conflict-zones.generated.ts"

VALID_TYPES = {"war", "insurgency", "tension", "frozen", "maritime_dispute"}


def ts_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug or "conflict"


def main() -> int:
    print("== build-conflicts ==")
    zones: list[dict] = []
    seen_ids: set[str] = set()
    problems: list[str] = []

    paths = sorted(WAVE2.glob("conflicts-*.json"))
    if WAVE3.exists():
        paths += sorted(WAVE3.glob("conflicts-*.json"))
    for path in paths:
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
            rows = payload["conflicts"] if isinstance(payload, dict) else payload
        except Exception as exc:  # noqa: BLE001
            problems.append(f"{path.name}: unreadable ({exc})")
            continue
        for raw in rows:
            try:
                name = str(raw["name"]).strip()
                ctype = str(raw["type"]).strip()
                if ctype not in VALID_TYPES:
                    problems.append(f"{path.name}/{name}: bad type {ctype!r}")
                    continue
                lat = float(raw["lat"])
                lng = float(raw["lng"])
                radius = max(30, min(900, int(raw.get("radiusKm") or 200)))
                parties = [str(p).strip().upper() for p in raw.get("parties") or [] if str(p).strip()]
                base = slugify(str(raw.get("id") or name))
                cid = base
                n = 2
                while cid in seen_ids:
                    cid = f"{base}-{n}"
                    n += 1
                seen_ids.add(cid)
                zones.append({
                    "id": cid,
                    "name": name,
                    "nameRu": str(raw.get("nameRu") or name).strip(),
                    "type": ctype,
                    "intensity": max(1, min(10, int(raw.get("intensity") or 5))),
                    "parties": parties,
                    "lat": round(lat, 4),
                    "lng": round(lng, 4),
                    "radiusKm": radius,
                    "since": str(raw.get("since") or "2024").strip(),
                    "note": str(raw.get("note") or "").strip(),
                    "noteRu": str(raw.get("noteRu") or "").strip(),
                    "source": str(raw.get("source") or "public").strip(),
                })
            except (KeyError, TypeError, ValueError) as exc:
                problems.append(f"{path.name}: bad record {raw!r} ({exc})")

    zones.sort(key=lambda z: (-z["intensity"], z["name"]))

    lines = [
        "/** GENERATED by scripts/build-conflicts.py — do not edit by hand. */",
        'import type { ConflictZone } from "./types";',
        "",
        "export const CONFLICT_ZONES: ConflictZone[] = [",
    ]
    for z in zones:
        lines.append("  {")
        for key in ("id", "name", "nameRu", "type", "since", "note", "noteRu", "source"):
            lines.append(f"    {key}: {ts_str(str(z[key]))},")
        lines.append(f"    intensity: {z['intensity']},")
        parties = ", ".join(ts_str(p) for p in z["parties"])
        lines.append(f"    parties: [{parties}],")
        lines.append(f"    lat: {z['lat']},")
        lines.append(f"    lng: {z['lng']},")
        lines.append(f"    radiusKm: {z['radiusKm']},")
        lines.append("  },")
    lines.append("];")
    lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")

    print(f"zones={len(zones)}")
    by_type: dict[str, int] = {}
    for z in zones:
        by_type[z["type"]] = by_type.get(z["type"], 0) + 1
    for t, c in sorted(by_type.items()):
        print(f"  {t}: {c}")
    if problems:
        print(f"problems ({len(problems)}):")
        for p in problems[:20]:
            print("  " + p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
