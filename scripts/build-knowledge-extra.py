# ────────────────────────────────────────────────────────────────────────────

def build_airdefense() -> int:
    networks: list = []
    for path in sorted(RESEARCH.glob("*.json")):
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        if isinstance(raw, dict) and isinstance(raw.get("networks"), list):
            networks += raw["networks"]
    out = [HEADER]
    out.append("export type AirDefenseTier =")
    out.append('  | "long" | "medium" | "short" | "manpads" | "abm" | "counter_uas";')
    out.append("")
    out.append("export interface AirDefenseSystem {")
    out.append("  iso: string;")
    out.append("  name: string;")
    out.append("  tier: AirDefenseTier;")
    out.append("  rangeKm: number | null;")
    out.append("  count: number | null;")
    out.append("  noteRu: string | null;")
    out.append("}")
    out.append("")
    out.append("export interface AirDefenseNetwork {")
    out.append("  iso: string;")
    out.append("  architectureRu: string;")
    out.append("  systems: AirDefenseSystem[];")
    out.append("}")
    out.append("")
    out.append("export const AIR_DEFENSE_NETWORKS: readonly AirDefenseNetwork[] = [")
    seen_ad: set[tuple] = set()
    for net in networks:
        iso = net.get("iso")
        if not isinstance(iso, str) or len(iso) != 3:
            missed.append(f"ad iso={iso!r}")
            continue
        out.append("  {")
        out.append(f"    iso: {ts(iso)},")
        out.append(f"    architectureRu: {ts(net.get('architectureRu') or '')},")
        out.append("    systems: [")
        for s in net.get("systems") or []:
            name = s.get("name")
            if not isinstance(name, str) or not name:
                continue
            if (iso, name) in seen_ad:
                continue
            seen_ad.add((iso, name))
            parts = [f"iso: {ts(iso)}", f"name: {ts(name)}", f"tier: {ts(s.get('tier') or 'medium')}",
                     f"rangeKm: {num(s.get('rangeKm'), 'ad.rangeKm')}", f"count: {num(s.get('count'), 'ad.count')}"]
            note = s.get("noteRu")
            parts.append(f"noteRu: {ts(note)}" if note else "noteRu: null")
            out.append("      { " + ", ".join(parts) + " },")
        out.append("    ],")
        out.append("  },")
    out.append("];")
    out.append("")
    return write_lines("airdefense.generated.ts", out)


