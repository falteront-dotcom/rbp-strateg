# ────────────────────────────────────────────────────────────────────────────

def build_missiles() -> int:
    # mimo пишет missiles.json и частями (_m*.json с {iso, systems}). Сканируем всё.
    arsenals: list = []
    for path in sorted(RESEARCH.glob("*.json")):
        try:
            raw = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        if isinstance(raw, dict) and isinstance(raw.get("arsenals"), list):
            arsenals += raw["arsenals"]
        elif isinstance(raw, list):
            for rec in raw:
                if isinstance(rec, dict) and "systems" in rec and "iso" in rec:
                    arsenals.append(rec)
    out = [HEADER]
    out.append("export type MissileType =")
    out.append('  | "icbm" | "irbm" | "mrbm" | "srbm" | "slbm" | "cruise" | "hypersonic" | "abm";')
    out.append("")
    out.append("export interface MissileSystem {")
    out.append("  iso: string;")
    out.append("  name: string;")
    out.append("  type: MissileType;")
    out.append("  rangeKm: number | null;")
    out.append("  warheadRu: string | null;")
    out.append("  count: number | null;")
    out.append("  status: string;")
    out.append("  noteRu: string | null;")
    out.append("}")
    out.append("")
    out.append("export const MISSILE_SYSTEMS: readonly MissileSystem[] = [")
    n = 0
    seen_ms: set[tuple] = set()
    for a in arsenals:
        iso = a.get("iso")
        if not isinstance(iso, str) or len(iso) != 3:
            missed.append(f"missile iso={iso!r}")
            continue
        for s in a.get("systems") or []:
            name = s.get("name")
            if not isinstance(name, str) or not name:
                continue
            if s.get("type") not in ("icbm", "irbm", "mrbm", "srbm", "slbm", "cruise", "hypersonic", "abm"):
                continue
            if (iso, name, s.get("type")) in seen_ms:
                continue
            seen_ms.add((iso, name, s.get("type")))
            out.append("  {")
            out.append(f"    iso: {ts(iso)},")
            out.append(f"    name: {ts(name)},")
            out.append(f"    type: {ts(s.get('type') or 'cruise')},")
            out.append(f"    rangeKm: {num(s.get('rangeKm'), 'rangeKm')},")
            out.append(f"    warheadRu: {ts(s.get('warheadRu')) if s.get('warheadRu') else 'null'},")
            out.append(f"    count: {num(s.get('count'), 'count')},")
            out.append(f"    status: {ts(s.get('status') or 'на вооружении')},")
            out.append(f"    noteRu: {ts(s.get('noteRu')) if s.get('noteRu') else 'null'},")
            out.append("  },")
            n += 1
    out.append("];")
    out.append("")
    return write_lines("missiles.generated.ts", out)


