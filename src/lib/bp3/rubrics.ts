// ─────────────────────────────────────────────────────────────────────────────
// BP Model 3.0 – Анкерные рубрики субъективных шкал (Rubrics)
// Волна 1 дорожной карты 3.0 (закрывает п. 3 критики 2.0)
//
// Проблема bp-v2: C4ISR, РЭБ и «моральный индекс» — числа 1–10 в базе
// без шкалы. Два аналитика дадут одной стране разные баллы, проверить
// и оспорить оценку невозможно — воспроизводимости нет, а для
// разведывательного продукта это брак.
//
// Решение: каждый балл привязан к анкеру — описанию наблюдаемого
// состояния армии, при котором ставится именно этот балл, плюс
// индикаторы (что наблюдать) и типичные свидетельства (где смотреть).
// Скорer обязан указать, какой анкер он применил; расхождение двух
// независимых проходов > 2 баллов уходит в арбитраж (combineTwoScorers).
// ─────────────────────────────────────────────────────────────────────────────

/** Вид рубрики */
export type RubricKind = "c4isr" | "ew" | "morale";

/** Один уровень шкалы 1–10 */
export interface RubricLevel {
  /** Балл уровня */
  score: number;
  /** Анкер: описание состояния, соответствующего баллу */
  anchorRu: string;
  /** Наблюдаемые индикаторы уровня */
  indicatorsRu: string[];
  /** Типичные свидетельства, по которым уровень проверяется */
  typicalEvidenceRu: string;
}

/** Полная рубрика шкалы */
export interface Rubric {
  kind: RubricKind;
  titleRu: string;
  descriptionRu: string;
  levels: RubricLevel[];
  /** Методические указания скореру */
  scoringGuidanceRu: string[];
}


