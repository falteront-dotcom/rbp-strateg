// ─────────────────────────────────────────────────────────────────────────────
//
// 1. Новый объект оценки начинается не с текста, а с рядов мониторинга:
//    сначала снапшоты и дельты, потом сводка. Сводка без рядов превращается
//    в мнение без опоры.
// 2. BLUF пишется последним по работе и первым по тексту: сначала суждения
//    и альтернативы, потом их свёртка в главный вывод.
// 3. Каждое суждение проходит три вопроса: какова вероятность по шкале
//    ICD 203; какова уверенность и почему именно такая; какое наблюдение
//    это суждение опровергнет.
// 4. Грейды источников не повышаются за авторитет издания: оценивается
//    метод и доступ к первичным данным. Заявления сторон конфликта не
//    поднимаются выше D без независимого подтверждения.
// 5. Альтернатива обязана быть различимой: если нельзя назвать наблюдение,
//    отличающее её от основной оценки, это не альтернатива, а риторика.
// 6. Перед публикацией сводка прогоняется через validateBriefing из
//    intel/icd203; ошибки валидатора — стоп-фактор, предупреждения —
//    предмет явного решения аналитика.
// 7. Листы наблюдения обновляются по итогам каждой сводки: пункты, по
//    которым наблюдение состоялось, уходят в хронику приложения; пороги
//    пересматриваются, если сработали ложно дважды подряд.
