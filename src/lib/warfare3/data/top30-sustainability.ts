/** Все ISO3-коды профилей в порядке списка */
export const TOP30_ISO3: string[] = TOP30_SUSTAINABILITY.map(
  (profile: CountrySustainabilityProfile): string => profile.iso3,
);

/**
 * Найти профиль устойчивости по ISO3-коду.
 * Возвращает undefined, если страны нет в топ-30.
 */
export function getSustainabilityProfile(
  iso3: string,
): CountrySustainabilityProfile | undefined {
  const normalized: string = iso3.trim().toUpperCase();
  return TOP30_SUSTAINABILITY.find(
    (profile: CountrySustainabilityProfile): boolean =>
      profile.iso3 === normalized,
  );
}

/**
 * Найти профиль устойчивости по ISO3-коду или выбросить ошибку.
 * Для движков, которым профиль нужен обязательно.
 */
export function requireSustainabilityProfile(
  iso3: string,
): CountrySustainabilityProfile {
  const profile: CountrySustainabilityProfile | undefined =
    getSustainabilityProfile(iso3);
  if (profile === undefined) {
    throw new Error(
      `Профиль устойчивости не найден для страны ${iso3}: ` +
        `доступны ${TOP30_ISO3.join(", ")}`,
    );
  }
  return profile;
}

